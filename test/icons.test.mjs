#!/usr/bin/env node
/**
 * Rail glyph test (Phase 4A).
 *
 * The rail must not contain hand-drawn icons: `scripts/extract-icons.mjs` copies
 * the sprite symbols chatgpt.com renders, `scripts/build-icons.mjs` turns them
 * into `lib/client/rail-icons.js`, and this test keeps the three in step. It
 * also pins the four-entry rail and the two sidebar display rules that the phase
 * introduced (super-agent row, Chat has no 项目).
 *
 * Run: node test/icons.test.mjs
 */

import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { read, skipSuite } from './evidence.mjs'
skipSuite(import.meta.url)

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

const capture = JSON.parse(read('docs/capture/icons.json'))
const generated = read('lib/client/rail-icons.js')
const rail = read('lib/client/rail.js')
const sessions = read('lib/client/sessions.js')
const buildScript = read('scripts/build-icons.mjs')

let failures = 0
let checks = 0
const check = (name, condition, detail) => {
  checks += 1
  if (condition) return
  failures += 1
  console.log(`FAIL  ${name}${detail === undefined ? '' : ` — ${detail}`}`)
}

// 1. capture: both states, real sprite paths, measured geometry.
{
  const names = Object.keys(capture.icons ?? {})
  check('capture holds at least the seven rail glyphs', names.length >= 7, names.join(','))
  for (const name of ['home', 'schedules', 'plugins', 'more', 'settings', 'agent', 'dot']) {
    check(`capture has ${name}`, names.includes(name))
  }
  for (const name of ['compose', 'folder', 'paperclip', 'mic', 'voice']) {
    check(`capture has the 4B glyph ${name}`, names.includes(name))
  }
  for (const [name, icon] of Object.entries(capture.icons)) {
    check(`${name} default is a real path`, typeof icon.default?.inner === 'string' && icon.default.inner.includes('<path'))
    check(`${name} selected exists`, icon.selectedEqualsDefault === true || typeof icon.selected?.inner === 'string')
    // `compose` is the one glyph chatgpt.com draws inline (the 新聊天 button's
    // own <svg>), so it is keyed by its source instead of a sprite symbol id.
    const symbol = icon.reference?.symbol ?? ''
    const inline = icon.reference?.inline === true
    check(`${name} keeps its sprite symbol id`, symbol.startsWith('codex-icon-') || inline, symbol)
  }
  const home = capture.icons.home
  check('home has a distinct filled selected twin', home.selectedEqualsDefault !== true && home.selected.inner !== home.default.inner)
  const geometry = capture.geometry ?? {}
  check('button is 36×36', geometry.button?.width === 36 && geometry.button?.height === 36, JSON.stringify(geometry.button))
  check('button radius is 10px', geometry.button?.radius === '10px', String(geometry.button?.radius))
  check('icon is 20×20', geometry.icon?.width === '20px' && geometry.icon?.height === '20px', JSON.stringify(geometry.icon))
  check('rail width is 52px', geometry.railWidth === '52px', String(geometry.railWidth))
}

// 2. generated fragment: every captured glyph, verbatim, both states.
{
  check('fragment is marked generated', generated.includes('GENERATED by scripts/build-icons.mjs'))
  check('fragment exposes one helper', generated.includes('function chatgptRailGlyph('))
  check('build script regenerates the fragment', buildScript.includes('rail-icons.js'))
  // Re-render the expected markup exactly as scripts/build-icons.mjs does.
  const markup = (shape, size) =>
    `<svg viewBox="${shape.viewBox ?? '0 0 20 20'}" width="${size}" height="${size}" aria-hidden="true" fill="currentColor">` +
    `${shape.inner.replace(/ xmlns="http:\/\/www\.w3\.org\/2000\/svg"/g, '')}</svg>`
  const sizes = { dot: 16 }
  for (const [name, icon] of Object.entries(capture.icons)) {
    check(`fragment carries ${name}`, generated.includes(`  ${name}: {`))
    const size = sizes[name] ?? 20
    check(
      `fragment copies ${name} default path verbatim`,
      generated.includes(JSON.stringify(markup(icon.default, size))),
      name
    )
    const selected = icon.selectedEqualsDefault === true ? icon.default : icon.selected
    check(`fragment copies ${name} selected path verbatim`, generated.includes(JSON.stringify(markup(selected, size))), name)
  }
  check('fragment uses currentColor', generated.includes('fill=\\"currentColor\\"'))
}

// 3. rail: P0-10A order — 首页/定时任务/插件/更多/项目 + 设置.
{
  const block = rail.slice(rail.indexOf('const CHATGPT_RAIL_ITEMS = ['), rail.indexOf('const CHATGPT_RAIL_SETTINGS_ITEM'))
  const ids = [...block.matchAll(/id: '([a-z]+)'/g)].map((match) => match[1])
  check('rail has 首页 plus four destinations', ids.length === 5, ids.join(','))
  check('rail order is 首页/定时任务/插件/更多/项目', ids.join(',') === 'home,schedules,plugins,more,projects', ids.join(','))
  check('projects opens the all-projects overview', /kind: 'projects'/.test(block) && /chatgptOpenProjectPage\(''\)/.test(rail))
  check('super-agent is not a rail button', !/id: 'agent'[^\n]*kind: 'panel'/.test(block))
  check('schedules is a primary host panel button', /id: 'schedules'[^\n]*panelId: 'schedules'/.test(block))
  check('plugins opens the plugin-manager main panel', /panelId: CHATGPT_PLUGINS_PANEL_ID/.test(block) && rail.includes("const CHATGPT_PLUGINS_PANEL_ID = 'plugins'"))
  check('plugins no longer detours through Settings', !rail.includes('chatgptOpenPluginsSettings') && !rail.includes('CHATGPT_PLUGINS_SECTION_RE'))
  check('settings is pinned below the spacer', rail.includes('CHATGPT_RAIL_SETTINGS_ITEM') && rail.indexOf('chatgpt-rail-spacer') < rail.indexOf('item: CHATGPT_RAIL_SETTINGS_ITEM'))
  check('settings opens the host modal', rail.includes('chatgptOpenSettings(bridge)') && rail.includes("id: 'settings', label: '设置'"))
  check('settings is also offered from the 更多 menu', rail.includes("{ id: 'settings', label: '设置', glyph: 'settings', onSelect: onSettings }"))
  check('more menu offers Chat/Work', rail.includes("id: 'chat', label: 'Chat'") && rail.includes("id: 'work', label: 'Work'"))
  const moreBlock = rail.slice(rail.indexOf('const moreItems = ['), rail.indexOf('  ]\n\n  return chatgptH'))
  check('more menu keeps Settings last', moreBlock.indexOf("{ id: 'settings', label: '设置'") > moreBlock.indexOf("{ id: 'work', label: 'Work'"))
  check('more menu offers super-agent', rail.includes("id: 'agent', label: 'Super-agent'"))
  check('every panel open goes through the guarded helper', rail.includes('chatgptSelectPanel(ctx, panelId)') && !rail.includes('ctx.layout.selectPanel'))
  check('no hand-drawn 20px rail glyphs left', !/CHATGPT_RAIL_ICONS/.test(rail))
  check('rail reads glyphs from the generated module', rail.includes('chatgptRailGlyph(name, selected)'))
  check('selected state is painted from data-cgpt-rail-state', read('lib/client/css/21-rail.css').includes("[data-cgpt-rail-state='selected']"))
  check('selected buttons expose data-selected', rail.includes("'data-selected': active ? 'true' : undefined"))
  check('selected destinations use a filled glyph', rail.includes("'data-cgpt-rail-glyph-state': active ? 'filled' : 'outline'") && rail.includes('chatgptRailItemGlyph'))
  check('定时任务 and 插件 selected states follow the real panel id', rail.includes('activePanel === item.panelId'))
  check('super-agent rail button is gone, not merely hidden', !/CHATGPT_RAIL_ITEMS[\s\S]{0,600}DOT_PANEL_ID/.test(block))
}

// 4. sidebar: super-agent row + the 项目 section is mode-independent (P0-19f).
{
  check('sidebar renders the super-agent row', sessions.includes("'data-cgpt-super-agent'"))
  check('super-agent row opens the dot panel through the guarded helper', sessions.includes('chatgptSelectPanel(ctx, DOT_PANEL_ID)'))
  check('super-agent row never touches ctx.layout directly', !sessions.includes('ctx.layout'))
  check('unread badge reads the plugin endpoint', sessions.includes("'/api/super-agent/ui/state'"))
  check('badge hidden at zero', sessions.includes('dotUnread > 0'))
  check('project section is not product-gated', !sessions.includes('showProjects') && sessions.includes("className: 'chatgpt-projects-section'"))
  check('最近 keeps project tags in both modes', sessions.includes('rows(page.recent, false, true)'))
  check('new chat goes through the product-aware starter', sessions.includes('chatgptStartProductSession(ctx, { agentPreset: preset, workspaceId })'))
  check('new chat + super-agent live in the fixed block outside the scrollport', sessions.includes("className: 'chatgpt-session-fixed'") && sessions.indexOf("className: 'chatgpt-session-fixed'") < sessions.indexOf("className: 'chatgpt-session-scroll'"))
  check('project row has no chevron and toggles only', sessions.includes("className: 'chatgpt-project-row'") && sessions.includes('onClick: () => toggleProject(project.id)') && !sessions.includes('className: \'chatgpt-project-toggle\''))
  check('hover menu anchors to the row right edge', sessions.includes('rect.right + 8'))
  check('running comes from the host status hook', sessions.includes('useSessionStatus') && sessions.includes('.running === true') && sessions.includes('data-cgpt-running-spinner'))
  check('internal Sessions stay out of the list', sessions.includes('internalSessionIds: dotState.internalIds'))
  check('the list mounts with layout injected', read('lib/client/entry.js').includes("'uiWorkspace', 'layout'"))
}

// 5. mode UI: segment only on a blank session; the note lives outside the card.
{
  const modeUi = read('lib/client/mode-ui.js')
  check('header segment hides on a started session', modeUi.includes('if (blank === false) return null'))
  // P0-16 removed the hint row only; `conversation.hero.options` still hosts the
  // (empty-state hidden) mode cards, so the check names the hint instead.
  check('P0-16: the hero hint row is gone', !modeUi.includes('chatgpt-hero-hint') && !modeUi.includes('ChatgptHeroHint') && !read('lib/client/entry.js').includes('hero mode hint'))
  const heroCss = read('lib/client/css/60-hero.css')
  check('hero composer hides the in-card note', heroCss.includes("[class*='_composerHero'] .chatgpt-readonly"))
}

console.log(`${failures === 0 ? 'PASS' : 'FAIL'}  ${checks - failures}/${checks} icon and rail checks`)
process.exit(failures === 0 ? 0 : 1)
