#!/usr/bin/env node
/**
 * P0-12 — the Host's task (todo) and goal panels are native again, and share
 * the composer column.
 *
 * Source contract:
 *   1. no skin rule may restyle the inside of either panel (header, title,
 *      progress, glyph, button, hover): those belong to
 *      `dsh-client-ui-conversation` / `dsh-client-ui-goal`;
 *   2. the only skin-owned declarations are the outer column widths, and both
 *      read `--dsh-chat-content-width` — the variable P0-11's splitter drives —
 *      exactly like the composer card and the transcript column;
 *   3. no skin JS builds a replacement panel (no `todo-panel` / `nLMEza` in the
 *      fragments).
 *
 * Evidence contract (`docs/m24.json`, generated by scripts/m24-panels.mjs):
 *   4. the fixed skin puts both panel edges within 1px of the card edge in both
 *      themes, and the transcript column is on the same edges;
 *   5. type, line-height and padding of the fixed panels equal native skin-off;
 *   6. the `before` tag records the pre-fix offset, the three states share one
 *      clip per panel/theme, and every named screenshot exists.
 *
 * Run: node test/m24.test.mjs
 */

import { existsSync, readFileSync, readdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (path) => readFileSync(join(ROOT, path), 'utf8')

let checks = 0
let failures = 0
const check = (name, condition, detail) => {
  checks += 1
  if (condition) return
  failures += 1
  console.log(`FAIL  ${name}${detail === undefined ? '' : ` — ${detail}`}`)
}

/* ---- 1. no skin styling inside either panel ---------------------------- */
const CSS_DIR = join(ROOT, 'lib', 'client', 'css')
const cssFiles = readdirSync(CSS_DIR).filter((file) => file.endsWith('.css')).sort()
const css = cssFiles.map((file) => readFileSync(join(CSS_DIR, file), 'utf8')).join('\n')
const stripped = css.replace(/\/\*[\s\S]*?\*\//g, '')
const rules = [...stripped.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map((match) => ({
  selector: match[1].trim().replace(/\s+/g, ' '),
  body: match[2].trim()
}))
const panelRules = rules.filter((rule) => /data-testid=['"]todo-panel['"]|nLMEza|lXshSW/.test(rule.selector))

check('exactly two skin rules touch the two panels', panelRules.length === 2, panelRules.map((rule) => rule.selector).join(' | '))
check('the todo rule only sets the outer width', panelRules.some((rule) => /\[data-testid=['"]todo-panel['"]\]$/.test(rule.selector) && rule.body === 'width: min(calc(100% - 2 * var(--dsh-composer-side-clearance, 16px)), var(--dsh-chat-content-width, var(--cgpt-msg-max, 920px)));'), panelRules.find((rule) => /todo-panel/.test(rule.selector))?.body)
check('the goal rule only sets the dock width', panelRules.some((rule) => /\.nLMEza_dock$/.test(rule.selector) && rule.body === 'width: min(calc(100% - 2 * var(--dsh-composer-side-clearance, 16px)), var(--dsh-chat-content-width, var(--cgpt-msg-max, 920px)));'), panelRules.find((rule) => /nLMEza/.test(rule.selector))?.body)
check('no rule targets the panel header/title/progress/glyph/button', !panelRules.some((rule) => /button|svg|hover|header|title|progress|lead|glyph|chevron|\.nLMEza_bar/.test(rule.selector)), panelRules.map((rule) => rule.selector).join(' | '))
check('no skin rule names a Host todo/goal CSS-module class', !rules.some((rule) => /lXshSW/.test(rule.selector)))
check('both widths read the splitter-driven column variable', panelRules.every((rule) => rule.body.includes('--dsh-chat-content-width') && !rule.body.includes('--dsh-chat-user-width')))
check('neither rule hardcodes a pixel width', !panelRules.some((rule) => /width:\s*\d+px/.test(rule.body)))

/* ---- 2. no self-made DOM for the panels -------------------------------- */
const fragments = readdirSync(join(ROOT, 'lib', 'client'))
  .filter((file) => file.endsWith('.js') && file !== 'client.js')
  .map((file) => readFileSync(join(ROOT, 'lib', 'client', file), 'utf8'))
  .join('\n')
const shared = readdirSync(join(ROOT, 'lib', 'shared'))
  .filter((file) => file.endsWith('.mjs'))
  .map((file) => readFileSync(join(ROOT, 'lib', 'shared', file), 'utf8'))
  .join('\n')
check('no fragment renders a todo/goal panel', !/todo-panel|nLMEza|lXshSW/.test(`${fragments}\n${shared}`))
check('the built bundle carries exactly the two width rules', (read('lib/client.js').match(/\[data-testid='todo-panel'\] \{/g) ?? []).length === 1 && (read('lib/client.js').match(/\.nLMEza_dock \{/g) ?? []).length === 1)
const bundleStripped = read('lib/client.js').replace(/\/\*[\s\S]*?\*\//g, '')
check('the deleted per-part rules are absent from the bundle', !bundleStripped.includes('nLMEza_bar') && !bundleStripped.includes('lXshSW'))

/* ---- 3. live evidence -------------------------------------------------- */
const doc = JSON.parse(read('docs/m24.json'))
const near = (a, b) => Math.abs(a - b) <= 1
const strip = (value) => JSON.parse(JSON.stringify(value, (name, entry) => (name === 'border' ? undefined : entry)))

check('evidence was generated against a tokenised URL', typeof doc.generatedAt === 'string' && /token?|redacted/.test(doc.source) && doc.deviceScaleFactor === 2)
check('both tags and both themes exist', ['before', 'after'].every((tag) => ['light', 'dark'].every((theme) => doc.tags[tag]?.[theme]?.task !== undefined && doc.tags[tag]?.[theme]?.goal !== undefined)))
check('every after assertion passes', doc.assertions.filter((row) => row.tag === 'after').every((row) => row.pass === true) && doc.assertions.filter((row) => row.tag === 'after').length === 8)
check('every before assertion records the misalignment', doc.assertions.filter((row) => row.tag === 'before').every((row) => row.pass === false && row.detail.left < -100 && row.detail.left === row.detail.right))

for (const tag of ['before', 'after']) {
  for (const theme of ['light', 'dark']) {
    for (const key of ['task', 'goal']) {
      const item = doc.tags[tag][theme][key]
      const native = doc.native[theme][key]
      const prefix = `${tag}/${theme}/${key}`
      if (tag === 'after') {
        check(`${prefix}: left/right/width within 1px of the card`, near(item.delta.left, 0) && near(item.delta.right, 0) && near(item.delta.width, 0), JSON.stringify(item.delta))
        check(`${prefix}: transcript column on the same edges`, near(item.delta.columnLeft, 0) && near(item.delta.columnRight, 0), JSON.stringify(item.delta))
        check(`${prefix}: type/line-height/padding equals native`, JSON.stringify(strip(item.typography)) === JSON.stringify(strip(native.typography)), JSON.stringify({ implementation: item.typography, native: native.typography }))
      }
      check(`${prefix}: clip matches native and the other tag`, JSON.stringify(item.clip) === JSON.stringify(native.clip) && JSON.stringify(item.clip) === JSON.stringify(doc.tags[tag === 'before' ? 'after' : 'before'][theme][key].clip), JSON.stringify(item.clip))
      check(`${prefix}: screenshot exists`, existsSync(join(ROOT, item.screenshot)), item.screenshot)
    }
  }
}
check('native frames were captured skin-off', doc.native.light.task.panel !== null && doc.native.light.goal.panel !== null && doc.native.light.task.card.width !== doc.tags.after.light.task.card.width, JSON.stringify({ nativeCard: doc.native.light.task.card.width, skinCard: doc.tags.after.light.task.card.width }))
for (const theme of ['light', 'dark']) {
  const splitter = doc.splitter?.[theme]
  check(`splitter/${theme}: card, column and panel move as one column`, splitter !== undefined && splitter.pass === true && splitter.moved >= 40 && splitter.after.card === splitter.after.column && splitter.after.card === splitter.after.panel && splitter.before.card === splitter.before.panel, JSON.stringify(splitter))
}
check('native keeps the Host 32px dock gutter (reference, not skin)', doc.native.light.task.delta.width === -32 && doc.native.dark.goal.delta.width === -32, JSON.stringify({ task: doc.native.light.task.delta, goal: doc.native.dark.goal.delta }))

console.log(`${checks - failures}/${checks} checks passed`)
if (failures > 0) process.exit(1)
