#!/usr/bin/env node
/**
 * build-icons.mjs — regenerate lib/client/rail-icons.js from docs/capture/icons.json.
 *
 * The rail glyphs are not hand-drawn: `scripts/extract-icons.mjs` copies the
 * sprite symbols the ChatGPT app itself renders (default + filled/selected
 * state), and this script turns that JSON into the concatenatable fragment the
 * browser bundle needs. Regenerating is the only way to edit the glyphs, so a
 * path can never be "cleaned up" by hand and lose the reference geometry.
 *
 *   node scripts/build-icons.mjs        (npm run icons; `npm run build` runs it first)
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const JSON_PATH = join(ROOT, 'docs', 'capture', 'icons.json')
const OUT_PATH = join(ROOT, 'lib', 'client', 'rail-icons.js')

const data = JSON.parse(readFileSync(JSON_PATH, 'utf8'))
const sizes = { dot: 16 }

/** Render one sprite symbol as a standalone inline `<svg>`. */
function markup(shape, size) {
  if (shape === null || shape === undefined) return null
  const viewBox = shape.viewBox ?? '0 0 20 20'
  const inner = String(shape.inner ?? '').replace(/ xmlns="http:\/\/www.w3.org\/2000\/svg"/g, '')
  return (
    `<svg viewBox="${viewBox}" width="${size}" height="${size}" aria-hidden="true" fill="currentColor">` +
    `${inner}</svg>`
  )
}

const entries = Object.entries(data.icons).map(([name, icon]) => {
  const size = sizes[name] ?? 20
  const fallback = icon.default
  const selected = icon.selectedEqualsDefault === true ? fallback : icon.selected
  return {
    name,
    reference: icon.reference?.symbol ?? null,
    default: markup(fallback, size),
    selected: markup(selected, size)
  }
})

const lines = []
lines.push('/**')
lines.push(' * dsh-chatgpt-ui — rail glyphs (GENERATED by scripts/build-icons.mjs).')
lines.push(' *')
lines.push(' * Source: docs/capture/icons.json, which `scripts/extract-icons.mjs` fills')
lines.push(' * from the icon sprite chatgpt.com serves (`' + (data.meta?.sprite ?? '') + '`).')
lines.push(' * Path data is copied verbatim: the rail must match the reference at the')
lines.push(' * pixel level, and a hand-redrawn gear drifts out of symmetry.')
lines.push(' *')
lines.push(' * Do not edit by hand: `npm run icons` regenerates this file.')
lines.push(' */')
lines.push('')
lines.push('/** 20px glyphs, default + selected (filled/emphasis) state. */')
lines.push('const CHATGPT_RAIL_GLYPHS = {')
for (const entry of entries) {
  lines.push(`  ${entry.name}: {`)
  lines.push(`    symbol: ${JSON.stringify(entry.reference)},`)
  lines.push(`    default: ${JSON.stringify(entry.default)},`)
  lines.push(`    selected: ${JSON.stringify(entry.selected)}`)
  lines.push('  },')
}
lines.push('}')
lines.push('')
lines.push('/**')
lines.push(' * Markup for one rail glyph.')
lines.push(' * @param {string} name - glyph key (home, schedules, plugins, more, settings, agent, dot).')
lines.push(' * @param {boolean} [selected] - use the filled/emphasis twin when one exists.')
lines.push(' * @returns {string} inline SVG markup, or an empty string for an unknown glyph.')
lines.push(' */')
lines.push('function chatgptRailGlyph(name, selected) {')
lines.push('  const glyph = CHATGPT_RAIL_GLYPHS[name]')
lines.push('  if (glyph === undefined) return \'\'')
lines.push('  return selected === true ? glyph.selected : glyph.default')
lines.push('}')
lines.push('')

const text = lines.join('\n')
const previous = (() => {
  try {
    return readFileSync(OUT_PATH, 'utf8')
  } catch {
    return ''
  }
})()
if (previous !== text) writeFileSync(OUT_PATH, text, 'utf8')
console.log(`${previous === text ? 'unchanged' : 'wrote'} lib/client/rail-icons.js (${entries.length} glyphs)`)
