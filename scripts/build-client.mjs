#!/usr/bin/env node
/**
 * Build lib/client.js from lib/client/{theme,styles,entry}.js + lib/client/css/*.css.
 *
 * Why a build step at all: the browser half is served as ONE module-loader
 * bundle (same shape as the shipped plugins, e.g. `window.__ModuleLoader__.load
 * ({ id, factory })`), and the module loader answers package specifiers, not
 * relative paths inside a package — so a served bundle cannot `require` a
 * sibling file of ours. Splitting the source keeps the files reviewable; this
 * script is the deterministic 60-line concatenator that puts them back together.
 *
 * No third-party bundler, no minifier, no dependency: the input is our own
 * three fragments, so plain concatenation is sufficient. It fails loudly on the
 * two things concatenation cannot handle (a stray import/export, a name clash).
 *
 * Usage: node scripts/build-client.mjs   (npm run build)
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CLIENT_DIR = join(ROOT, 'lib', 'client')
const CSS_DIR = join(CLIENT_DIR, 'css')

/** Shared modules inlined first: ESM sources that the node tests import directly. */
const SHARED = ['mode-core.mjs', 'layout-core.mjs', 'sessions-core.mjs', 'composer-core.mjs', 'project-core.mjs', 'connection-core.mjs']

/** Fragments, in evaluation order. Must stay dependency-free statements. */
const FRAGMENTS = [
  'theme.js',
  'styles.js',
  'connection.js',
  'locales.js',
  'mode.js',
  'mode-ui.js',
  'brand.js',
  'rail-icons.js',
  'menu-icons.js',
  'rail.js',
  'sessions.js',
  'composer.js',
  'trigger-ui.js',
  'project.js',
  'messages.js',
  'entry.js'
]

/** Stylesheets, in cascade order (the numeric file-name prefix carries the rank,
 *  so a new slice is picked up without editing this list). */
const CSS_FILES = readdirSync(CSS_DIR)
  .filter((name) => name.endsWith('.css'))
  .sort()

if (!CSS_FILES.includes('90-fallback.css')) {
  throw new Error('90-fallback.css must exist: it is the documented last slice')
}

const BANNER = `/**
 * dsh-chatgpt-ui — browser bundle. GENERATED by scripts/build-client.mjs.
 * Do not edit: edit lib/client/*.js or lib/client/css/*.css and rebuild.
 *
 * Loaded by the DSH Web client through this package's "./client" export. The
 * factory body is a concatenation of the fragments listed in the build script;
 * the only runtime dependencies are the module loader and React (through the
 * loader's require, for the two slot components).
 *
 * Copyright (c) 2026 the dsh-chatgpt-ui authors. MIT licensed.
 * The token-layer technique (override tokens instead of registering a theme id)
 * follows @deepseek-ai/dsh-client-ui-theme's documented API; the stylesheet
 * lifecycle here is original code (see docs/licenses.md).
 */
`

const FOOTER = `
    module.exports.apply = apply
    module.exports.inject = inject
    return module.exports
  }
})
`

/** Inline one shared ESM module by dropping its `export` keywords. */
function readShared(file) {
  const text = readFileSync(join(CLIENT_DIR, '..', 'shared', file), 'utf8')
  for (const [line, index] of text.split('\n').entries()) {
    if (/^\s*import\b/.test(line) || /^\s*export\s+(?:default|\{)/.test(line)) {
      throw new Error(
        `${file}:${index + 1} cannot be inlined (no imports, no default/named export lists): ${line.trim()}`
      )
    }
  }
  return text.replace(/^export (function|const|class|let) /gm, '$1 ').trimEnd()
}

/** Read one fragment and reject anything a concatenation would break. */
function readFragment(file) {
  const text = readFileSync(join(CLIENT_DIR, file), 'utf8')
  for (const [line, index] of text.split('\n').entries()) {
    if (/^\s*(?:import|export)\b/.test(line)) {
      throw new Error(
        `${file}:${index + 1} uses an ESM import/export, which cannot survive concatenation: ${line.trim()}`
      )
    }
  }
  return text.trimEnd()
}

const css = CSS_FILES.map((file) => {
  const text = readFileSync(join(CSS_DIR, file), 'utf8').trimEnd()
  return `/* ---- ${file} ---- */\n${text}`
}).join('\n\n')

const body = [
  BANNER,
  'window.__ModuleLoader__.load({',
  "  id: 'dsh-chatgpt-ui',",
  '  factory: (require) => {',
  '    const module = { exports: {} }',
  '    const exports = module.exports',
  '',
  `    /** Stylesheet text of lib/client/css/, in cascade order. */`,
  `    const CHATGPT_CSS_TEXT = ${JSON.stringify(css)}`,
  '',
  ...SHARED.map((file) => readShared(file)),
  ...FRAGMENTS.map((file) => readFragment(file)),
  ''
].join('\n')

const output = join(ROOT, 'lib', 'client.js')
writeFileSync(output, `${body}${FOOTER}`, 'utf8')

const bytes = Buffer.byteLength(`${body}${FOOTER}`)
console.log(`wrote lib/client.js (${bytes} bytes): ${SHARED.length + FRAGMENTS.length} fragments, ${CSS_FILES.length} stylesheets`)
